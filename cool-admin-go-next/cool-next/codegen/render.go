func componentDependencies(component Component, dependencies []Dependency) []Dependency {
	var result []Dependency
	for _, dependency := range dependencies {
		consumer := dependency.consumer
		if consumer.module == component.module && consumer.packagePath == component.packagePath && consumer.name == component.name {
			result = append(result, dependency)
		}
	}
	sort.Slice(result, func(left, right int) bool {
		return result[left].parameterIndex < result[right].parameterIndex
	})
	return result
}

func writeGeneratedFunction(
	source *strings.Builder,
	graph *Graph,
	modules []renderModule,
	fragments []DescriptorFragment,
	descriptorProviders map[string]Provider,
	providers []Provider,
	components []renderComponent,
	dependencies []Dependency,
	services []renderService,
	controllers []renderController,
	imports *importManager,
) {
	producers := graph.Producers()
	consumers := graph.Consumers()
	publisher, hasPublisher := graph.Publisher()
	consumerAdapter, hasConsumerAdapter := graph.ConsumerAdapter()
	hasProducers := len(producers) > 0
	hasConsumers := len(consumers) > 0
	workerDefinition := Component{module: frameworkModuleKey, packagePath: outboxPackagePath, name: "NewWorker"}
	consumerRuntimeDefinition := Component{module: frameworkModuleKey, packagePath: outboxPackagePath, name: "NewConsumerRuntime"}
	graphProviders := append([]Provider(nil), providers...)
	graphProviders = appendProviderIfMissing(graphProviders, Provider{kind: ProviderKindComponent, module: frameworkModuleKey, packagePath: appHTTPPackagePath, name: "New", typ: "*" + appHTTPPackagePath + ".Transport"})
	graphProviders = appendProviderIfMissing(graphProviders, Provider{kind: ProviderKindComponent, module: frameworkModuleKey, packagePath: grpcPackagePath, name: "New", typ: "*" + grpcPackagePath + ".Transport"})
	graphProviders = appendProviderIfMissing(graphProviders, Provider{kind: ProviderKindComponent, module: frameworkModuleKey, packagePath: databasePackagePath, name: "Runtime", typ: "*" + databasePackagePath + ".Runtime"})
	if hasProducers {
		graphProviders = appendProviderIfMissing(graphProviders, Provider{kind: ProviderKindComponent, module: workerDefinition.module, packagePath: workerDefinition.packagePath, name: workerDefinition.name, typ: "*" + outboxPackagePath + ".Worker"})
	}
	if hasConsumers {
		graphProviders = appendProviderIfMissing(graphProviders, Provider{kind: ProviderKindComponent, module: consumerRuntimeDefinition.module, packagePath: consumerRuntimeDefinition.packagePath, name: consumerRuntimeDefinition.name, typ: "*" + outboxPackagePath + ".ConsumerRuntime"})
	}
	source.WriteString("func generatedGraph() module.Graph {\n")
	source.WriteString("\treturn module.MustBuildGraph(module.GraphInput{\n")
	source.WriteString("\t\tModules: []module.ModuleDefinition{\n")
	for _, current := range modules {
		fmt.Fprintf(source, "\t\t\t{Key: %q, Name: %q, Description: %q, Order: %d", current.key, current.config.name, current.config.description, current.config.order)
		writeReferences(source, "Middlewares", current.references, imports)
		writeReferences(source, "GlobalMiddlewares", current.references, imports)
		source.WriteString("},\n")
	}
	source.WriteString("\t\t\t{Key: \".framework\", Name: \"Cool Framework\", Description: \"应用基础设施\"},\n")
	source.WriteString("\t\t},\n")
	if len(controllers) > 0 {
		source.WriteString("\t\tControllers: []coreroute.ControllerDefinition{\n")
		for _, current := range controllers {
			writeControllerDefinition(source, current)
		}
		source.WriteString("\t\t},\n")
		source.WriteString("\t\tRoutes: []coreroute.Definition{\n")
		for _, current := range controllers {
			for _, route := range current.declaration.routes {
				writeRouteDefinition(source, current, route)
			}
		}
		source.WriteString("\t\t},\n")
	}
	source.WriteString("\t\tProviders: []module.ProviderDefinition{\n")
	for _, provider := range graphProviders {
		source.WriteString("\t\t\t")
		writeProviderDefinition(source, provider, false)
		source.WriteString(",\n")
	}
	source.WriteString("\t\t},\n")
	definedComponents := make(map[string]bool, len(graphProviders))
	componentDefinitions := make([]Component, 0, len(graphProviders))
	constructorsByComponent := make(map[string]Constructor, len(components))
	for _, current := range components {
		key := componentKey(current.component.module, current.component.packagePath, current.component.name)
		constructorsByComponent[key] = current.constructor
	}
	assemblyComponents := append([]renderComponent(nil), components...)
	if authorizer, exists := authorizerComponent(components); exists {
		assemblyComponents = authorizerPrerequisites(authorizer, components, dependencies)
		for _, current := range components {
			if !authorizerDependency(authorizer, current, components, dependencies) {
				assemblyComponents = append(assemblyComponents, current)
			}
		}
	}
	for _, provider := range graphProviders {
		if provider.kind != ProviderKindComponent && provider.kind != ProviderKindConsumerDefinition {
			continue
		}
		if provider.packagePath == appHTTPPackagePath || provider.packagePath == grpcPackagePath {
			continue
		}
		definition := Component{module: provider.module, packagePath: provider.packagePath, name: provider.name}
		key := componentKey(definition.module, definition.packagePath, definition.name)
		if definedComponents[key] || constructorsByComponent[key].name != "" {
			continue
		}
		componentDefinitions = append(componentDefinitions, definition)
		definedComponents[key] = true
	}
	for _, current := range assemblyComponents {
		key := componentKey(current.component.module, current.component.packagePath, current.component.name)
		if definedComponents[key] {
			continue
		}
		componentDefinitions = append(componentDefinitions, current.component)
		definedComponents[key] = true
	}
	for _, provider := range graphProviders {
		if (provider.packagePath != appHTTPPackagePath && provider.packagePath != grpcPackagePath) || provider.name != "New" {
			continue
		}
		definition := Component{module: provider.module, packagePath: provider.packagePath, name: provider.name}
		key := componentKey(definition.module, definition.packagePath, definition.name)
		if definedComponents[key] {
			continue
		}
		componentDefinitions = append(componentDefinitions, definition)
		definedComponents[key] = true
	}
	source.WriteString("\t\tComponents: []module.ComponentDefinition{\n")
	for _, definition := range componentDefinitions {
		writeComponentDefinition(source, definition)
	}
	source.WriteString("\t\t},\n")
	source.WriteString("\t\tLifecycles: []module.LifecycleDefinition{\n")
	for _, definition := range componentDefinitions {
		constructor := constructorsByComponent[componentKey(definition.module, definition.packagePath, definition.name)]
		hasInitializer := constructor.hasInitializer
		hasStarter := constructor.hasStarter
		hasStopper := constructor.hasStopper
		hasSupervisor := false
		if hasProducers && sameComponent(definition, workerDefinition) {
			hasStarter = true
			hasStopper = true
			hasSupervisor = true
		}
		if hasConsumers && sameComponent(definition, consumerRuntimeDefinition) {
			hasInitializer = true
			hasStarter = true
			hasStopper = true
			hasSupervisor = true
		}
		fmt.Fprintf(
			source,
			"\t\t\t{Component: module.ComponentDefinition{Module: %q, PackagePath: %q, Name: %q}, Initializer: %t, Starter: %t, Stopper: %t, Supervisor: %t},\n",
			definition.module,
			definition.packagePath,
			definition.name,
			hasInitializer,
			hasStarter,
			hasStopper,
			hasSupervisor,
		)
	}
	source.WriteString("\t\t},\n")
	source.WriteString("\t\tTransports: []module.ComponentDefinition{\n")
	for _, current := range components {
		if !current.constructor.hasTransport {
			continue
		}
		fmt.Fprintf(source, "\t\t\t{Module: %q, PackagePath: %q, Name: %q},\n", current.component.module, current.component.packagePath, current.component.name)
	}
	fmt.Fprintf(source, "\t\t\t{Module: %q, PackagePath: %q, Name: \"New\"},\n", frameworkModuleKey, appHTTPPackagePath)
	fmt.Fprintf(source, "\t\t\t{Module: %q, PackagePath: %q, Name: \"New\"},\n", frameworkModuleKey, grpcPackagePath)
	source.WriteString("\t\t},\n")
	source.WriteString("\t\tDependencies: []module.DependencyDefinition{\n")
	for _, dependency := range dependencies {
		consumer := dependency.consumer
		fmt.Fprintf(source, "\t\t\t{Consumer: module.ComponentDefinition{Module: %q, PackagePath: %q, Name: %q}, ParameterIndex: %d, Provider: ", consumer.module, consumer.packagePath, consumer.name, dependency.parameterIndex)
		writeProviderDefinition(source, dependency.provider, true)
		source.WriteString("},\n")
	}
	if hasProducers && hasPublisher {
		fmt.Fprintf(source, "\t\t\t{Consumer: module.ComponentDefinition{Module: %q, PackagePath: %q, Name: %q}, ParameterIndex: 0, Provider: ", workerDefinition.module, workerDefinition.packagePath, workerDefinition.name)
		writeProviderDefinition(source, componentProvider(graph, publisher), true)
		source.WriteString("},\n")
	}
	if hasConsumers && hasConsumerAdapter {
		fmt.Fprintf(source, "\t\t\t{Consumer: module.ComponentDefinition{Module: %q, PackagePath: %q, Name: %q}, ParameterIndex: 0, Provider: ", consumerRuntimeDefinition.module, consumerRuntimeDefinition.packagePath, consumerRuntimeDefinition.name)
		writeProviderDefinition(source, componentProvider(graph, consumerAdapter), true)
		source.WriteString("},\n")
		for index, consumer := range consumers {
			fmt.Fprintf(source, "\t\t\t{Consumer: module.ComponentDefinition{Module: %q, PackagePath: %q, Name: %q}, ParameterIndex: %d, Provider: ", consumerRuntimeDefinition.module, consumerRuntimeDefinition.packagePath, consumerRuntimeDefinition.name, index+1)
			writeProviderDefinition(source, componentProvider(graph, consumer), true)
			source.WriteString("},\n")
		}
	}
	source.WriteString("\t\t},\n")
	source.WriteString("\t\tDescriptors: []module.DescriptorDefinition{\n")
	for _, fragment := range fragments {
		key := descriptorKey(fragment.module, fragment.entityPackage, fragment.entity)
		fmt.Fprintf(source, "\t\t\t{Module: %q, Table: %q, Provider: ", fragment.module, fragment.table)
		writeProviderDefinition(source, descriptorProviders[key], true)
		source.WriteString("},\n")
	}
	source.WriteString("\t\t},\n")
	source.WriteString("\t\tOutbox: module.OutboxDefinition{\n")
	writeOutboxRoleDefinitions(source, "Producers", producers)
	writeOutboxRoleDefinitions(source, "Consumers", consumers)
	if hasPublisher {
		writeOutboxRoleDefinitions(source, "Publishers", []Component{publisher})
	}
	if hasConsumerAdapter {
		writeOutboxRoleDefinitions(source, "ConsumerAdapters", []Component{consumerAdapter})
	}
	if hasProducers {
		writeOutboxRoleDefinitions(source, "Workers", []Component{workerDefinition})
	}
	if hasConsumers {
		writeOutboxRoleDefinitions(source, "ConsumerRuntimes", []Component{consumerRuntimeDefinition})
	}
	source.WriteString("\t\t},\n")
	source.WriteString("\t})\n}\n")

	source.WriteString("\nfunc assemble(ctx context.Context, input app.AssembleInput")
	for index := range modules {
		fmt.Fprintf(source, ", identity%d module.Identity", index)
	}
	source.WriteString(") (*app.Assembly, error) {\n")
	source.WriteString("\tassembly := app.NewAssembly()\n")
	source.WriteString("\tinfrastructure, err := generatedInfrastructureConfig(ctx, input.RootSource())\n")
	source.WriteString("\tif err != nil {\n\t\treturn assembly, err\n\t}\n")
	if hasProducers || hasConsumers {
		source.WriteString("\tif !infrastructure.Cool.Outbox.Enabled {\n")
		source.WriteString("\t\treturn assembly, exception.Core(\"应用存在 Producer 或 Consumer，不能关闭 Outbox\")\n\t}\n")
	}

	for index, current := range modules {
		configAlias := imports.alias(current.config.packagePath)
		fmt.Fprintf(source, "\tconfig%d, err := module.Compile(ctx, identity%d, %s.ModuleConfig(), input.ModuleDefaultsSource())\n", index, index, configAlias)
		source.WriteString("\tif err != nil {\n\t\treturn assembly, err\n\t}\n")
		configUsed := false
		for _, dependency := range dependencies {
			if dependency.provider.kind == ProviderKindConfig && dependency.provider.module == current.key {
				configUsed = true
				break
			}
		}
		if !configUsed {
			fmt.Fprintf(source, "\t_ = config%d\n", index)
		}
	}
	usedProviders := make(map[string]bool)
	for _, dependency := range dependencies {
		usedProviders[renderProviderKey(dependency.provider)] = true
	}
	for _, fragment := range fragments {
		name := generatedIdentifier(fragment.module, fragment.entityPackage, fragment.entity)
		fmt.Fprintf(source, "\tdescriptor_%s := %s()\n", name, descriptorFunctionName(fragment))
	}
	if len(fragments) > 0 || hasProducers || hasConsumers || len(controllers) > 0 || hasSeedModules(modules) {
		source.WriteString("\truntime, recycler, err := generatedDataRuntime(ctx, infrastructure")
		for _, fragment := range fragments {
			fmt.Fprintf(source, ", descriptor_%s", generatedIdentifier(fragment.module, fragment.entityPackage, fragment.entity))
		}
		source.WriteString(")\n")
		source.WriteString("\tif err != nil {\n\t\treturn assembly, err\n\t}\n")
		source.WriteString("\t_ = runtime\n\t_ = recycler\n")
		if hasAuthProviders(graph.Providers()) {
			fmt.Fprintf(source, "\tassembly.AddComponent(module.ComponentDefinition{Module: %q, PackagePath: %q, Name: %q}, app.Hooks{})\n", frameworkModuleKey, authPackagePath, "Service")
			fmt.Fprintf(source, "\tassembly.AddComponent(module.ComponentDefinition{Module: %q, PackagePath: %q, Name: %q}, app.Hooks{})\n", frameworkModuleKey, authPackagePath, "Store")
		}
		if hasFrameworkProvider(graph.Providers(), authBcryptPackagePath, "Verifier") {
			fmt.Fprintf(source, "\tassembly.AddComponent(module.ComponentDefinition{Module: %q, PackagePath: %q, Name: %q}, app.Hooks{})\n", frameworkModuleKey, authBcryptPackagePath, "Verifier")
		}
		fmt.Fprintf(source, "\tassembly.AddComponent(module.ComponentDefinition{Module: %q, PackagePath: %q, Name: %q}, app.Hooks{})\n", frameworkModuleKey, databasePackagePath, "Runtime")
	}
	if hasSeedModules(modules) {
		source.WriteString("\tseedRuntime, err := seed.NewRuntime(runtime,\n")
		for _, current := range modules {
			if !current.seedDB && !current.seedMenu {
				continue
			}
			db, menu := "nil", "nil"
			if current.seedDB {
				db = "seedDB_" + generatedIdentifier(current.key)
			}
			if current.seedMenu {
				menu = "seedMenu_" + generatedIdentifier(current.key)
			}
			fmt.Fprintf(source, "\t\tseed.NewDefinition(%q, seed.NewData(%s, %s)", current.key, db, menu)
			for _, fragment := range fragments {
				if fragment.module == current.key {
					fmt.Fprintf(source, ", descriptor_%s", generatedIdentifier(fragment.module, fragment.entityPackage, fragment.entity))
				}
			}
			source.WriteString("),\n")
		}
		source.WriteString("\t)\n")
		source.WriteString("\tif err != nil { return assembly, exception.WrapCore(err, \"构造种子运行时失败\") }\n")
		source.WriteString("\tif err = seedRuntime.OnInit(ctx); err != nil { return assembly, exception.WrapCore(err, \"导入模块种子失败\") }\n")
	}
	if hasProducers || hasConsumers {
		source.WriteString("\toutboxStore, err := outboxstore.New(runtime)\n")
		source.WriteString("\tif err != nil {\n\t\treturn assembly, exception.WrapCore(err, \"构造 Outbox Store 失败\")\n\t}\n")
	}
	if hasProducers {
		source.WriteString("\tenqueuer, err := outbox.NewEnqueuer(runtime, outboxStore, infrastructure.Cool.Outbox.EnqueueLimits())\n")
		source.WriteString("\tif err != nil {\n\t\treturn assembly, exception.WrapCore(err, \"构造 Outbox Enqueuer 失败\")\n\t}\n")
	}
	for _, fragment := range fragments {
		name := generatedIdentifier(fragment.module, fragment.entityPackage, fragment.entity)
		if usedProviders[renderProviderKey(Provider{kind: ProviderKindBase, module: fragment.baseProvider.module, packagePath: fragment.entityPackage, name: fragment.baseProvider.name, typ: fragment.baseProvider.typ})] {
			fmt.Fprintf(source, "\tbase_%s, err := %s(descriptor_%s, runtime, recycler)\n", name, fragment.baseProvider.name, name)
			source.WriteString("\tif err != nil {\n\t\treturn assembly, err\n\t}\n")
		} else {
			fmt.Fprintf(source, "\tvar base_%s *coreservice.Base[%s.%s, uint64]\n", name, imports.alias(fragment.entityPackage), fragment.entity)
			fmt.Fprintf(source, "\t_ = base_%s\n", name)
		}
	}
	if hasAuthProviders(graph.Providers()) {
		source.WriteString("\tjwtService, err := auth.NewJWT(infrastructure.Cool.Auth.JWT)\n")
		source.WriteString("\tif err != nil { return assembly, exception.WrapCore(err, \"构造 JWT 服务失败\") }\n")
		source.WriteString("\tsessionAdapter, err := auth.NewSessionStore(ctx, infrastructure.Cool.Auth.Session)\n")
		source.WriteString("\tif err != nil { return assembly, exception.WrapCore(err, \"构造 Session Store 失败\") }\n")
		authorizer, exists := authorizerComponent(components)
		if exists {
			for _, prerequisite := range authorizerPrerequisites(authorizer, components, dependencies) {
				writeComponentConstruction(source, prerequisite, dependencies, modules, fragments, descriptorProviders, components, componentResultRequired(prerequisite, graph, dependencies, modules, controllers, components), imports)
			}
		}
		authorizerValue := "nil"
		if exists {
			authorizerValue = componentVariableName(authorizer.component)
		}
		fmt.Fprintf(source, "\tauthService, err := auth.NewService(jwtService, sessionAdapter, %s)\n", authorizerValue)
		source.WriteString("\tif err != nil { return assembly, exception.WrapCore(err, \"构造 Auth 服务失败\") }\n")
	}
	if hasFrameworkProvider(graph.Providers(), authBcryptPackagePath, "Verifier") {
		source.WriteString("\tbcryptVerifier, err := authbcrypt.New(authbcrypt.Config{})\n")
		source.WriteString("\tif err != nil { return assembly, exception.WrapCore(err, \"构造 bcrypt 验证器失败\") }\n")
	}
	for _, current := range components {
		if authorizer, exists := authorizerComponent(components); exists && authorizerDependency(authorizer, current, components, dependencies) {
			continue
		}
		writeComponentConstruction(source, current, dependencies, modules, fragments, descriptorProviders, components, componentResultRequired(current, graph, dependencies, modules, controllers, components), imports)
	}
	for _, current := range controllers {
		arguments := make([]string, len(current.declaration.parameterTypes))
		for index, parameter := range current.declaration.parameterTypes {
			arguments[index], _ = componentExpressionForType(parameter, components)
		}
		name := "controller_" + generatedIdentifier(current.module, current.declaration.packagePath, current.declaration.name)
		fmt.Fprintf(source, "\t%s := %s(%s)\n", name, controllerFunctionName(current), strings.Join(arguments, ", "))
	}
	writeEPSPublish(source, controllers, fragments)
	writeHTTPInstallerClosure(source, modules, fragments, services, controllers, components, imports, hasAuthProviders(graph.Providers()))
	source.WriteString("\thttpTransport, err := apphttp.New(infrastructure.Cool.Transports.HTTP, generatedHTTPInstaller)\n")
	source.WriteString("\tif err != nil {\n\t\treturn assembly, exception.WrapCore(err, \"构造 HTTP Transport 失败\")\n\t}\n")
	fmt.Fprintf(source, "\tassembly.AddTransport(module.ComponentDefinition{Module: %q, PackagePath: %q, Name: \"New\"}, httpTransport, app.Hooks{})\n", frameworkModuleKey, appHTTPPackagePath)
	source.WriteString("\tgrpcTransport, err := coolgrpc.New(infrastructure.Cool.Transports.GRPC, GRPCRegistrar(), nil, nil)\n")
	source.WriteString("\tif err != nil {\n\t\treturn assembly, exception.WrapCore(err, \"构造 gRPC Transport 失败\")\n\t}\n")
	fmt.Fprintf(source, "\tassembly.AddTransport(module.ComponentDefinition{Module: %q, PackagePath: %q, Name: \"New\"}, grpcTransport, app.Hooks{})\n", frameworkModuleKey, grpcPackagePath)
	if hasProducers {
		publisherExpression := componentVariableName(publisher)
		fmt.Fprintf(source, "\toutboxWorker, err := outbox.NewWorker(outboxStore, %s, infrastructure.Cool.Outbox.WorkerConfig(), nil, nil)\n", publisherExpression)
		source.WriteString("\tif err != nil {\n\t\treturn assembly, exception.WrapCore(err, \"构造 Outbox Worker 失败\")\n\t}\n")
		fmt.Fprintf(source, "\tassembly.AddComponent(module.ComponentDefinition{Module: %q, PackagePath: %q, Name: %q}, app.Hooks{Starter: outboxWorker, Stopper: outboxWorker, Supervisor: outboxWorker})\n", workerDefinition.module, workerDefinition.packagePath, workerDefinition.name)
	}
	if hasConsumers {
		definitions := make([]string, len(consumers))
		for index, consumer := range consumers {
			definitions[index] = componentVariableName(consumer)
		}
		fmt.Fprintf(source, "\toutboxDeliverer, err := outbox.NewDeliverer(runtime, outboxStore, infrastructure.Cool.Outbox.ConsumerConfig(), %s)\n", strings.Join(definitions, ", "))
		source.WriteString("\tif err != nil {\n\t\treturn assembly, exception.WrapCore(err, \"构造 Outbox Deliverer 失败\")\n\t}\n")
		fmt.Fprintf(source, "\toutboxConsumerRuntime, err := outbox.NewConsumerRuntime(%s, outboxStore, outboxDeliverer)\n", componentVariableName(consumerAdapter))
		source.WriteString("\tif err != nil {\n\t\treturn assembly, exception.WrapCore(err, \"构造 Consumer Runtime 失败\")\n\t}\n")
		fmt.Fprintf(source, "\tassembly.AddComponent(module.ComponentDefinition{Module: %q, PackagePath: %q, Name: %q}, app.Hooks{Initializer: outboxConsumerRuntime, Starter: outboxConsumerRuntime, Stopper: outboxConsumerRuntime, Supervisor: outboxConsumerRuntime})\n", consumerRuntimeDefinition.module, consumerRuntimeDefinition.packagePath, consumerRuntimeDefinition.name)
	}
	source.WriteString("\treturn assembly, nil\n}\n")
	source.WriteString("\nfunc Generated() app.Definition {\n\tgraph := generatedGraph()\n\treturn app.Define(graph, func(ctx context.Context, input app.AssembleInput) (*app.Assembly, error) {\n\t\treturn assemble(ctx, input")
	for index := range modules {
		fmt.Fprintf(source, ", graph.Modules()[%d].Identity()", index)
	}
	source.WriteString(")\n\t})\n}\n")
}

