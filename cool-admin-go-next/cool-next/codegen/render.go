func writeDOValueDeclaration(source *strings.Builder, fragment DescriptorFragment) {
	name := doValueTypeName(fragment)
	fmt.Fprintf(source, "type %s struct {\n\tstate coreentity.DOValue\n\tdata %s\n}\n\n", name, fragment.doName)
	fmt.Fprintf(source, "func (value *%s) Has(field string) bool { return value.state.Has(field) }\n\n", name)
	fmt.Fprintf(source, "func (value *%s) IsNull(field string) bool { return value.state.IsNull(field) }\n\n", name)
	fmt.Fprintf(source, "func (value *%s) SetColumn(field string, input any) error {\n", name)
	source.WriteString("\tif err := value.state.SetColumn(field, input); err != nil {\n\t\treturn err\n\t}\n")
	source.WriteString("\tif value.state.IsNull(field) {\n\t\tinput = gdb.Raw(\"NULL\")\n\t}\n")
	source.WriteString("\tswitch field {\n")
	for _, field := range fragment.fields {
		fmt.Fprintf(source, "\tcase %q:\n\t\tvalue.data.%s = input\n", field.json, field.declaration)
	}
	source.WriteString("\t}\n\treturn nil\n}\n\n")
	fmt.Fprintf(source, "func (value *%s) DBData() any { return value.data }\n\n", name)
}

