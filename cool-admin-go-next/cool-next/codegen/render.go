func writeComponentConstruction(source *strings.Builder, current renderComponent, dependencies []Dependency, modules []renderModule, fragments []DescriptorFragment, descriptorProviders map[string]Provider, components []renderComponent, resultRequired bool, imports *importManager) {
	componentName := componentVariableName(current.component)
	currentDependencies := componentDependencies(current.component, dependencies)
	arguments := make([]string, len(currentDependencies))
	for index, dependency := range currentDependencies {
		arguments[index], _ = providerExpression(dependency.provider, modules, fragments, descriptorProviders, components)
	}
	call := imports.alias(current.constructor.packagePath) + "." + current.constructor.name + "(" + strings.Join(arguments, ", ") + ")"
	errorMessage := "构造组件 " + current.component.packagePath + "." + current.component.name + " 失败"
	switch {
	case resultRequired && constructorReturnsError(current.constructor):
		fmt.Fprintf(source, "\t%s, err := %s\n", componentName, call)
		fmt.Fprintf(source, "\tif err != nil {\n\t\treturn assembly, exception.WrapCore(err, %q)\n\t}\n", errorMessage)
	case resultRequired:
		fmt.Fprintf(source, "\t%s := %s\n", componentName, call)
	case constructorReturnsError(current.constructor):
		fmt.Fprintf(source, "\tif _, err := %s; err != nil {\n\t\treturn assembly, exception.WrapCore(err, %q)\n\t}\n", call, errorMessage)
	default:
		fmt.Fprintf(source, "\t%s\n", call)
	}
	hooksName := "hooks_" + generatedIdentifier(current.component.module, current.component.packagePath, current.component.name)
	fmt.Fprintf(source, "\t%s := app.Hooks{}\n", hooksName)
	if current.constructor.hasInitializer {
		fmt.Fprintf(source, "\t%s.Initializer = %s\n", hooksName, componentName)
	}
	if current.constructor.hasStarter {
		fmt.Fprintf(source, "\t%s.Starter = %s\n", hooksName, componentName)
	}
	if current.constructor.hasStopper {
		fmt.Fprintf(source, "\t%s.Stopper = %s\n", hooksName, componentName)
	}
	definitionName := "definition_" + generatedIdentifier(current.component.module, current.component.packagePath, current.component.name)
	fmt.Fprintf(source, "\t%s := module.ComponentDefinition{Module: %q, PackagePath: %q, Name: %q}\n", definitionName, current.component.module, current.component.packagePath, current.component.name)
	if current.constructor.hasTransport {
		transportName := "transport_" + generatedIdentifier(current.component.module, current.component.packagePath, current.component.name)
		fmt.Fprintf(source, "\tvar %s app.Transport = %s\n", transportName, componentName)
		fmt.Fprintf(source, "\tassembly.AddTransport(%s, %s, %s)\n", definitionName, transportName, hooksName)
	} else {
		fmt.Fprintf(source, "\tassembly.AddComponent(%s, %s)\n", definitionName, hooksName)
	}
}

func componentResultRequired(current renderComponent, graph *Graph, dependencies []Dependency, modules []renderModule, controllers []renderController, components []renderComponent) bool {
	constructor := current.constructor
	if constructor.hasInitializer || constructor.hasStarter || constructor.hasStopper || constructor.hasTransport ||
		constructor.isConsumerDefinition || constructor.isPublisher || constructor.isConsumerAdapter {
		return true
	}
	for _, dependency := range dependencies {
		provider := dependency.provider
		if (provider.kind == ProviderKindComponent || provider.kind == ProviderKindConsumerDefinition) &&
			provider.module == current.component.module && provider.packagePath == current.component.packagePath && provider.name == current.component.name {
			return true
		}
	}
	if hasAuthProviders(graph.Providers()) {
		if authorizer, exists := authorizerComponent(components); exists && sameComponent(authorizer.component, current.component) {
			return true
		}
	} else if len(controllers) > 0 && implementsHTTPAuthenticator(constructor.resultType) {
		return true
	}
	for _, controller := range controllers {
		for _, parameter := range controller.declaration.parameterTypes {
			if types.AssignableTo(constructor.resultType, parameter) {
				return true
			}
		}
		for _, reference := range modulesReferences(controller.module, modules) {
			if component, exists := middlewareComponent(controller.module, reference.symbol, modules, components); exists && sameComponent(component.component, current.component) {
				return true
			}
		}
		for _, symbol := range controller.declaration.middleware {
			if component, exists := middlewareComponent(controller.module, symbol, modules, components); exists && sameComponent(component.component, current.component) {
				return true
			}
		}
		for _, route := range controller.declaration.routes {
			if route.kind == coreroute.KindCRUD {
				if component, exists := componentForType(controller.declaration.serviceType, components); exists && sameComponent(component.component, current.component) {
					return true
				}
			} else if !isPackageHandler(route.handler) {
				if component, exists := handlerComponent(route.handler, components); exists && sameComponent(component.component, current.component) {
					return true
				}
			}
			for _, symbol := range route.middleware {
				if component, exists := middlewareComponent(controller.module, symbol, modules, components); exists && sameComponent(component.component, current.component) {
					return true
				}
			}
		}
	}

	return false
}

func modulesReferences(moduleKey string, modules []renderModule) []Reference {
	for _, current := range modules {
		if current.key == moduleKey {
			return current.references
		}
	}

	return nil
}

func sameComponent(left, right Component) bool {
	return left.module == right.module && left.packagePath == right.packagePath && left.name == right.name
}

func authorizerComponent(components []renderComponent) (renderComponent, bool) {
	for _, component := range components {
		method := types.NewMethodSet(types.Unalias(component.constructor.resultType)).Lookup(nil, "Authorize")
		if method == nil {
			continue
		}
		signature, ok := method.Obj().Type().(*types.Signature)
		if ok && signature.Params().Len() == 2 && signature.Results().Len() == 2 &&
			isContextType(signature.Params().At(0).Type()) && types.Identical(signature.Results().At(0).Type(), types.Typ[types.Bool]) &&
			types.Identical(signature.Results().At(1).Type(), types.Universe.Lookup("error").Type()) {
			return component, true
		}
	}
	return renderComponent{}, false
}

func authorizerPrerequisites(authorizer renderComponent, components []renderComponent, dependencies []Dependency) []renderComponent {
	var result []renderComponent
	for _, component := range components {
		if authorizerDependency(authorizer, component, components, dependencies) {
			result = append(result, component)
		}
	}
	return result
}

func authorizerDependency(authorizer, candidate renderComponent, components []renderComponent, dependencies []Dependency) bool {
	needed := map[string]bool{componentVariableName(authorizer.component): true}
	changed := true
	for changed {
		changed = false
		for _, dependency := range dependencies {
			if !needed[componentVariableName(dependency.consumer)] {
				continue
			}
			for _, component := range components {
				if component.component.module == dependency.provider.module && component.component.packagePath == dependency.provider.packagePath && component.component.name == dependency.provider.name {
					key := componentVariableName(component.component)
					if !needed[key] {
						needed[key] = true
						changed = true
					}
				}
			}
		}
	}
	return needed[componentVariableName(candidate.component)]
}

func validateControllerDependencies(controllers []renderController, components []renderComponent) error {
	for _, controller := range controllers {
		for index, parameter := range controller.declaration.parameterTypes {
			matches := 0
			for _, component := range components {
				if types.AssignableTo(component.constructor.resultType, parameter) {
					matches++
				}
			}
			if matches == 0 {
				return renderError("CG098", fmt.Sprintf("Controller %s 的第 %d 个参数缺少可构造组件", controller.declaration.name, index+1), controller.declaration.position)
			}
			if matches > 1 {
				return renderError("CG098", fmt.Sprintf("Controller %s 的第 %d 个参数匹配多个组件", controller.declaration.name, index+1), controller.declaration.position)
			}
		}
	}
	return nil
}

func componentVariableName(component Component) string {
	return "component_" + generatedIdentifier(component.module, component.packagePath, component.name)
}

func providerExpression(provider Provider, modules []renderModule, fragments []DescriptorFragment, descriptorProviders map[string]Provider, components []renderComponent) (string, bool) {
	switch provider.kind {
	case ProviderKindConfig:
		for index, current := range modules {
			if current.key == provider.module {
				return fmt.Sprintf("config%d.Config()", index), true
			}
		}
	case ProviderKindSeed:
		for _, current := range modules {
			if current.key == provider.module {
				db, menu := "nil", "nil"
				if current.seedDB {
					db = "seedDB_" + generatedIdentifier(current.key)
				}
				if current.seedMenu {
					menu = "seedMenu_" + generatedIdentifier(current.key)
				}
				return fmt.Sprintf("seed.NewData(%s, %s)", db, menu), true
			}
		}
	case ProviderKindDescriptor:
		for _, fragment := range fragments {
			key := descriptorKey(fragment.module, fragment.entityPackage, fragment.entity)
			if descriptorProviders[key] == provider {
				return "descriptor_" + generatedIdentifier(fragment.module, fragment.entityPackage, fragment.entity), true
			}
		}
	case ProviderKindBase:
		for _, fragment := range fragments {
			if fragment.baseProvider.module == provider.module && fragment.baseProvider.name == provider.name {
				return "base_" + generatedIdentifier(fragment.module, fragment.entityPackage, fragment.entity), true
			}
		}
	case ProviderKindComponent, ProviderKindConsumerDefinition:
		for _, current := range components {
			if current.component.module == provider.module && current.component.packagePath == provider.packagePath && current.component.name == provider.name {
				return componentVariableName(current.component), true
			}
		}
		// 框架非构造器 Provider（如数据库 Runtime）使用局部变量名
		if provider.module == frameworkModuleKey && provider.packagePath == databasePackagePath && provider.name == "Runtime" {
			return "runtime", true
		}
		if provider.module == frameworkModuleKey && provider.packagePath == authPackagePath {
			switch provider.name {
			case "Service":
				return "authService", true
			case "Codec":
				return "jwtService", true
			case "Store":
				return "sessionAdapter", true
			}
		}
		if provider.module == frameworkModuleKey && provider.packagePath == authBcryptPackagePath && provider.name == "Verifier" {
			return "bcryptVerifier", true
		}
	case ProviderKindEnqueuer:
		return "enqueuer", true
	}
	return "", false
}

func hasAuthProviders(providers []Provider) bool {
	for _, provider := range providers {
		if provider.module == frameworkModuleKey && provider.packagePath == authPackagePath {
			return true
		}
	}
	return false
}

func hasFrameworkProvider(providers []Provider, packagePath, name string) bool {
	for _, provider := range providers {
		if provider.module == frameworkModuleKey && provider.packagePath == packagePath && provider.name == name {
			return true
		}
	}
	return false
}

func validateProviderExpressions(dependencies []Dependency, modules []renderModule, fragments []DescriptorFragment, descriptorProviders map[string]Provider, components []renderComponent) error {
	for _, dependency := range dependencies {
		if _, ok := providerExpression(dependency.provider, modules, fragments, descriptorProviders, components); !ok {
			return renderError("CG088", "Provider 无法映射到静态装配局部变量", dependency.position)
		}
	}
	return nil
}

