func validateHTTPDependencies(
	modules []renderModule,
	fragments []DescriptorFragment,
	services []renderService,
	controllers []renderController,
	components []renderComponent,
	hasFrameworkAuth bool,
) error {
	if len(controllers) == 0 {
		return nil
	}
	authenticators := 0
	if hasFrameworkAuth {
		authenticators++
	}
	for _, component := range components {
		if implementsHTTPAuthenticator(component.constructor.resultType) {
			authenticators++
		}
	}
	if authenticators != 1 {
		return renderError("CG105", "HTTP 路由必须匹配唯一 Authenticator 组件", controllers[0].declaration.position)
	}
	for _, current := range modules {
		for _, reference := range current.references {
			if _, exists := middlewareComponent(current.key, reference.symbol, modules, components); !exists {
				return renderError("CG106", "HTTP 中间件缺少可构造组件或未实现 Handle", reference.position)
			}
		}
	}
	for _, current := range controllers {
		for _, symbol := range current.declaration.middleware {
			if _, exists := middlewareComponent(current.module, symbol, modules, components); !exists {
				return renderError("CG106", "Controller 中间件缺少可构造组件或未实现 Handle", current.declaration.position)
			}
		}
		for _, route := range current.declaration.routes {
			for _, symbol := range route.middleware {
				if _, exists := middlewareComponent(current.module, symbol, modules, components); !exists {
					return renderError("CG106", "Route 中间件缺少可构造组件或未实现 Handle", route.position)
				}
			}
			if route.kind == coreroute.KindCRUD {
				_, serviceExists := renderServiceForController(current, services)
				_, componentExists := componentForType(current.declaration.serviceType, components)
				_, descriptorExists := descriptorForType(current.declaration.entityType, fragments)
				if !serviceExists || !componentExists || !descriptorExists {
					return renderError("CG107", "CRUD 路由缺少 Service 组件或 Descriptor", route.position)
				}
				continue
			}
			if !isPackageHandler(route.handler) {
				if _, exists := handlerComponent(route.handler, components); !exists {
					return renderError("CG108", "自定义 Route Handler 缺少可构造接收者", route.position)
				}
			}
		}
	}

	return nil
}

func implementsHTTPAuthenticator(value types.Type) bool {
	selection := types.NewMethodSet(types.Unalias(value)).Lookup(nil, "AuthenticateHTTP")
	if selection == nil {
		return false
	}
	signature, matches := selection.Obj().Type().(*types.Signature)
	if !matches || signature.Params().Len() != 6 || signature.Results().Len() != 2 ||
		!isContextType(signature.Params().At(0).Type()) ||
		!types.Identical(signature.Params().At(5).Type(), types.Typ[types.Bool]) ||
		!isContextType(signature.Results().At(0).Type()) ||
		!types.Identical(signature.Results().At(1).Type(), types.Universe.Lookup("error").Type()) {
		return false
	}
	for index := 1; index < 5; index++ {
		if !types.Identical(signature.Params().At(index).Type(), types.Typ[types.String]) {
			return false
		}
	}

	return true
}

func implementsHTTPMiddleware(value types.Type) bool {
	selection := types.NewMethodSet(types.Unalias(value)).Lookup(nil, "Handle")
	if selection == nil {
		return false
	}
	signature, matches := selection.Obj().Type().(*types.Signature)
	if !matches || signature.Params().Len() != 1 || signature.Results().Len() != 0 {
		return false
	}
	pointer, matches := types.Unalias(signature.Params().At(0).Type()).(*types.Pointer)
	if !matches {
		return false
	}
	named, matches := types.Unalias(pointer.Elem()).(*types.Named)

	return matches && named.Obj() != nil && named.Obj().Pkg() != nil &&
		named.Obj().Pkg().Path() == ghttpPackagePath && named.Obj().Name() == "Request"
}

func middlewareComponent(moduleKey, symbol string, modules []renderModule, components []renderComponent) (renderComponent, bool) {
	var packagePath string
	for _, current := range modules {
		if current.key == moduleKey {
			parts := strings.Split(symbol, ".")
			if len(parts) < 2 {
				return renderComponent{}, false
			}
			packagePath = current.config.packagePath + "/" + strings.Join(parts[:len(parts)-1], "/")
			symbol = parts[len(parts)-1]
			break
		}
	}
	for _, component := range components {
		if component.component.module == moduleKey && component.component.packagePath == packagePath &&
			component.component.name == symbol && implementsHTTPMiddleware(component.constructor.resultType) {
			return component, true
		}
	}

	return renderComponent{}, false
}

func componentForType(target types.Type, components []renderComponent) (renderComponent, bool) {
	for _, component := range components {
		if types.AssignableTo(component.constructor.resultType, target) {
			return component, true
		}
	}

	return renderComponent{}, false
}

func handlerComponent(reference coreroute.CallableRef, components []renderComponent) (renderComponent, bool) {
	for _, component := range components {
		pointer, matches := types.Unalias(component.constructor.resultType).(*types.Pointer)
		if !matches {
			continue
		}
		named, matches := types.Unalias(pointer.Elem()).(*types.Named)
		if matches && named.Obj() != nil && named.Obj().Pkg() != nil &&
			named.Obj().Pkg().Path() == reference.PackagePath && named.Obj().Name() == reference.Symbol {
			return component, true
		}
	}

	return renderComponent{}, false
}

func renderServiceForController(controller renderController, services []renderService) (renderService, bool) {
	pointer, matches := types.Unalias(controller.declaration.serviceType).(*types.Pointer)
	if !matches {
		return renderService{}, false
	}
	target, matches := types.Unalias(pointer.Elem()).(*types.Named)
	if !matches {
		return renderService{}, false
	}
	for _, service := range services {
		if service.declaration.typ != nil && types.Identical(service.declaration.typ, target) {
			return service, true
		}
	}

	return renderService{}, false
}

func descriptorForType(target types.Type, fragments []DescriptorFragment) (DescriptorFragment, bool) {
	for _, fragment := range fragments {
		if types.Identical(types.Unalias(fragment.entityType), types.Unalias(target)) {
			return fragment, true
		}
	}

	return DescriptorFragment{}, false
}

func isPackageHandler(reference coreroute.CallableRef) bool {
	return strings.HasPrefix(reference.Type, "func(")
}

func writeHTTPInstallerClosure(
	source *strings.Builder,
	modules []renderModule,
	fragments []DescriptorFragment,
	services []renderService,
	controllers []renderController,
	components []renderComponent,
	imports *importManager,
	hasFrameworkAuth bool,
) {
	if len(controllers) == 0 {
		source.WriteString("\tgeneratedHTTPInstaller := func(server *ghttp.Server) error {\n")
		source.WriteString("\t\tif server == nil {\n\t\t\treturn exception.Core(\"HTTP Server 未初始化\")\n\t\t}\n")
		source.WriteString("\t\treturn nil\n\t}\n")

		return
	}
	source.WriteString("\tbinder, err := corecontroller.NewBinder(infrastructure.Cool.CRUD)\n")
	source.WriteString("\tif err != nil {\n\t\treturn assembly, exception.WrapCore(err, \"构造 HTTP Binder 失败\")\n\t}\n")
	source.WriteString("\tdispatcher, err := crud.NewDispatcher(runtime.Runner())\n")
	source.WriteString("\tif err != nil {\n\t\treturn assembly, exception.WrapCore(err, \"构造 CRUD Dispatcher 失败\")\n\t}\n")
	source.WriteString("\tdescriptorResolver := corecontroller.DescriptorResolverFunc(func(value any) (coreentity.Metadata, bool) {\n")
	source.WriteString("\t\tswitch value.(type) {\n")
	for _, fragment := range fragments {
		fmt.Fprintf(
			source,
			"\t\tcase %s.%s:\n\t\t\treturn descriptor_%s, true\n",
			imports.alias(fragment.entityPackage),
			fragment.entity,
			generatedIdentifier(fragment.module, fragment.entityPackage, fragment.entity),
		)
	}
	source.WriteString("\t\tdefault:\n\t\t\treturn nil, false\n\t\t}\n\t})\n")
	authenticator := "authService"
	if !hasFrameworkAuth {
		authenticator = componentVariableName(httpAuthenticatorComponent(components).component)
	}
	source.WriteString("\tgeneratedHTTPInstaller := func(server *ghttp.Server) error {\n")
	source.WriteString("\t\tif server == nil {\n\t\t\treturn exception.Core(\"HTTP Server 未初始化\")\n\t\t}\n")
	source.WriteString("\t\tserver.Use(corecontroller.NewResponseMiddleware(nil))\n")
	for _, current := range modules {
		for _, reference := range current.references {
			if reference.group != "GlobalMiddlewares" {
				continue
			}
			component, _ := middlewareComponent(current.key, reference.symbol, modules, components)
			fmt.Fprintf(source, "\t\tserver.Use(%s.Handle)\n", componentVariableName(component.component))
		}
	}
	for _, controller := range controllers {
		for _, route := range controller.declaration.routes {
			writeHTTPRouteInstall(source, modules, fragments, services, controller, route, components, authenticator, imports)
		}
	}
	source.WriteString("\t\treturn nil\n\t}\n")
}

func httpAuthenticatorComponent(components []renderComponent) renderComponent {
	for _, component := range components {
		if implementsHTTPAuthenticator(component.constructor.resultType) {
			return component
		}
	}

	return renderComponent{}
}

func writeHTTPRouteInstall(
	source *strings.Builder,
	modules []renderModule,
	fragments []DescriptorFragment,
	services []renderService,
	controller renderController,
	route RouteDeclaration,
	components []renderComponent,
	authenticator string,
	imports *importManager,
) {
	indent := "\t\t"
	if route.developmentOnly {
		source.WriteString("\t\tif gmode.IsDevelop() {\n")
		indent = "\t\t\t"
	}
	pattern := route.method + ":" + route.path
	routeName := generatedIdentifier(controller.module, route.method, route.path)
	ignoreToken := slices.Contains(route.tags, "ignoreToken")
	fmt.Fprintf(
		source,
		"%scontextMiddleware_%s, err := apphttp.NewContextMiddleware(%s, %q, %t)\n",
		indent,
		routeName,
		authenticator,
		route.path,
		ignoreToken,
	)
	fmt.Fprintf(source, "%sif err != nil {\n%s\treturn exception.WrapCore(err, %q)\n%s}\n", indent, indent, "构造 HTTP 路由中间件失败: "+route.method+" "+route.path, indent)
	fmt.Fprintf(source, "%sserver.BindMiddleware(%q, contextMiddleware_%s)\n", indent, pattern, routeName)
	writeHTTPRouteMiddlewares(source, indent, pattern, controller, route, modules, components)
	fmt.Fprintf(source, "%sserver.BindHandler(%q, func(ctx context.Context, _ *corecontroller.HTTPRequest) (any, error) {\n", indent, pattern)
	writeHTTPHandlerCall(source, indent+"\t", fragments, services, controller, route, components, imports)
	fmt.Fprintf(source, "%s})\n", indent)
	if route.developmentOnly {
		source.WriteString("\t\t}\n")
	}
}

func writeHTTPRouteMiddlewares(
	source *strings.Builder,
	indent string,
	pattern string,
	controller renderController,
	route RouteDeclaration,
	modules []renderModule,
	components []renderComponent,
) {
	var middleware []string
	for _, current := range modules {
		if current.key != controller.module {
			continue
		}
		for _, reference := range current.references {
			if reference.group == "Middlewares" {
				component, _ := middlewareComponent(current.key, reference.symbol, modules, components)
				middleware = append(middleware, componentVariableName(component.component)+".Handle")
			}
		}
	}
	for _, symbol := range controller.declaration.middleware {
		component, _ := middlewareComponent(controller.module, symbol, modules, components)
		middleware = append(middleware, componentVariableName(component.component)+".Handle")
	}
	for _, symbol := range route.middleware {
		component, _ := middlewareComponent(controller.module, symbol, modules, components)
		middleware = append(middleware, componentVariableName(component.component)+".Handle")
	}
	if len(middleware) > 0 {
		fmt.Fprintf(source, "%sserver.BindMiddleware(%q, %s)\n", indent, pattern, strings.Join(middleware, ", "))
	}
}

func writeHTTPHandlerCall(
	source *strings.Builder,
	indent string,
	fragments []DescriptorFragment,
	services []renderService,
	controller renderController,
	route RouteDeclaration,
	components []renderComponent,
	imports *importManager,
) {
	if route.kind == coreroute.KindCustom {
		writeCustomHTTPHandlerCall(source, indent, route, components, imports)

		return
	}
	service, _ := renderServiceForController(controller, services)
	component, _ := componentForType(controller.declaration.serviceType, components)
	fragment, _ := descriptorForType(controller.declaration.entityType, fragments)
	componentName := componentVariableName(component.component)
	controllerName := "controller_" + generatedIdentifier(controller.module, controller.declaration.packagePath, controller.declaration.name)
	mode := serviceActionModeName(service, route.handler.Method)
	adapter := serviceActionAdapterName(service, route.handler.Method)
	descriptor := "descriptor_" + generatedIdentifier(fragment.module, fragment.entityPackage, fragment.entity)
	entityType := imports.alias(fragment.entityPackage) + "." + fragment.entity
	switch route.handler.Method {
	case "Add":
		fmt.Fprintf(source, "%sreturn corecontroller.HandleAdd[%s, uint64](ctx, binder, dispatcher, descriptorResolver, %s, %s, %s, func(scopeCtx context.Context, input coreservice.AddInput[%s]) (coreservice.AddResult[uint64], error) {\n", indent, entityType, controllerName, mode, descriptor, entityType)
		fmt.Fprintf(source, "%s\treturn %s(scopeCtx, %s, input)\n%s})\n", indent, adapter, componentName, indent)
	case "Delete":
		fmt.Fprintf(source, "%sreturn corecontroller.HandleDelete[%s, uint64](ctx, binder, dispatcher, descriptorResolver, %s, %s, %s, func(scopeCtx context.Context, input coreservice.DeleteInput[uint64]) error {\n", indent, entityType, controllerName, mode, descriptor)
		fmt.Fprintf(source, "%s\treturn %s(scopeCtx, %s, input)\n%s})\n", indent, adapter, componentName, indent)
	case "Update":
		fmt.Fprintf(source, "%sreturn corecontroller.HandleUpdate[%s, uint64](ctx, binder, dispatcher, descriptorResolver, %s, %s, %s, func(scopeCtx context.Context, input coreservice.UpdateInput[%s, uint64]) error {\n", indent, entityType, controllerName, mode, descriptor, entityType)
		fmt.Fprintf(source, "%s\treturn %s(scopeCtx, %s, input)\n%s})\n", indent, adapter, componentName, indent)
	case "Info":
		if route.handler.HasRequest {
			writeCRUDDTOCall(source, indent, route, controllerName, mode, adapter, componentName, imports)
			return
		}
		fmt.Fprintf(source, "%sreturn corecontroller.HandleInfo[uint64](ctx, binder, dispatcher, descriptorResolver, %s, %s, func(scopeCtx context.Context, input uint64) (any, error) {\n", indent, controllerName, mode)
		fmt.Fprintf(source, "%s\treturn %s(scopeCtx, %s, input)\n", indent, adapter, componentName)
		fmt.Fprintf(source, "%s})\n", indent)
	case "List", "Page":
		if route.handler.HasRequest {
			writeCRUDDTOCall(source, indent, route, controllerName, mode, adapter, componentName, imports)
			return
		}
		fmt.Fprintf(source, "%sreturn corecontroller.HandleQuery(ctx, binder, dispatcher, descriptorResolver, %s, crud.Action%s, %s, func(scopeCtx context.Context, input coreservice.Query) (any, error) {\n", indent, controllerName, route.handler.Method, mode)
		fmt.Fprintf(source, "%s\treturn %s(scopeCtx, %s, input)\n", indent, adapter, componentName)
		fmt.Fprintf(source, "%s})\n", indent)
	}
}

func writeCRUDDTOCall(source *strings.Builder, indent string, route RouteDeclaration, controllerName, mode, adapter, componentName string, imports *importManager) {
	dtoType := imports.alias(route.handler.RequestPackagePath) + "." + route.handler.RequestType
	fmt.Fprintf(source, "%sreturn corecontroller.HandleCRUDDTO[%s](ctx, binder, coreroute.Bind%s, dispatcher, descriptorResolver, %s, crud.Action%s, %s, func(scopeCtx context.Context, input *%s) (any, error) {\n", indent, dtoType, bindSourceName(route.bind), controllerName, route.handler.Method, mode, dtoType)
	fmt.Fprintf(source, "%s\treturn %s(scopeCtx, %s, input)\n", indent, adapter, componentName)
	fmt.Fprintf(source, "%s})\n", indent)
}

func writeCustomHTTPHandlerCall(source *strings.Builder, indent string, route RouteDeclaration, components []renderComponent, imports *importManager) {
	target := imports.alias(route.handler.PackagePath) + "." + route.handler.Method
	if !isPackageHandler(route.handler) {
		component, _ := handlerComponent(route.handler, components)
		target = componentVariableName(component.component) + "." + route.handler.Method
	}
	policy := "coreroute.TransactionPolicy{}"
	if route.transaction.IsNonTransactional() {
		policy = "coreroute.NonTransactional()"
	}
	if route.handler.HasRequest {
		dtoType := imports.alias(route.handler.RequestPackagePath) + "." + route.handler.RequestType
		fmt.Fprintf(source, "%sreturn corecontroller.HandleDTO[%s](ctx, binder, coreroute.Bind%s, runtime.Runner(), %s, func(scopeCtx context.Context, input *%s) (any, error) {\n", indent, dtoType, bindSourceName(route.bind), policy, dtoType)
		writeInvokeResult(source, indent+"\t", target+"(scopeCtx, input)", route.handler.ReturnsValue)
		fmt.Fprintf(source, "%s})\n", indent)

		return
	}
	fmt.Fprintf(source, "%sreturn corecontroller.HandleNoDTO(ctx, runtime.Runner(), %s, func(scopeCtx context.Context) (any, error) {\n", indent, policy)
	writeInvokeResult(source, indent+"\t", target+"(scopeCtx)", route.handler.ReturnsValue)
	fmt.Fprintf(source, "%s})\n", indent)
}

func writeInvokeResult(source *strings.Builder, indent, call string, returnsValue bool) {
	if returnsValue {
		fmt.Fprintf(source, "%sreturn %s\n", indent, call)

		return
	}
	fmt.Fprintf(source, "%serr := %s\n%sreturn nil, err\n", indent, call, indent)
}

func writeStringField(source *strings.Builder, field string, values []string) {
	if len(values) == 0 {
		return
	}
	quoted := make([]string, len(values))
	for index, value := range values {
		quoted[index] = strconv.Quote(value)
	}
	fmt.Fprintf(source, ", %s: []string{%s}", field, strings.Join(quoted, ", "))
}

func corerouteFactoryReference(declaration ControllerDeclaration) coreroute.CallableRef {
	parameters := make([]string, len(declaration.parameterTypes))
	for index, parameter := range declaration.parameterTypes {
		parameters[index] = types.TypeString(parameter, qualifier)
	}

	return coreroute.CallableRef{
		PackagePath: declaration.packagePath,
		Symbol:      declaration.name,
		Type:        "func(" + strings.Join(parameters, ", ") + ") " + controllerPackagePath + ".Definition",
	}
}

